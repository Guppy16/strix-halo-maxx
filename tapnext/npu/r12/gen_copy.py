"""Round 12: a 2D-strided copy in 32 B units as a modulo-scheduled asm loop (r11/msched.py).

gated_b (mm8.cc flag 3) copies the pair's stash behind its own panels: 18 rows of 288 B from 320 B slots (64 B aligned) to
576 B rows at +288 (32 B aligned). In C++ (16 B vectors, Peano's indexed loop) that cost ~6,100 cycles per tile (r12
differential g11-r12gNOSTASH). Here: one vlda.2d + one vst.2d of a 256-bit w register per 32 B, II 1.

    extern "C" void cpy32(const void *src /*p0*/, void *dst /*p1*/, int trips /*r0*/, int src_jump /*r1*/,
                          int dst_jump /*r2*/, int row_m1 /*r3*/)
copies trips * U units of 32 B: rows of (row_m1 + 1) units; the last unit of a row steps src by src_jump and dst by dst_jump
bytes instead of 32 (2D post-modify: stride - 32 * row_m1). The copy's units must not overlap (a later unit's load never reads an earlier unit's store).

    python3 r12/gen_copy.py OUT.s [--ii N]
"""

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "r11"))
sys.path.insert(0, str(HERE))
from msched import Loop, Op  # noqa: E402

LDA_W = "VLDA_2D_dmw_lda_w"
ST_W = "VST_2D_dmw_sts_w"


def ops():
    return [
        Op("L", "lda", "vlda.2d {w.wl}, [p0], d0", defs=[("w", "wl", 7)], mem=("ld", "src"), instr=LDA_W),
        Op("S", "st", "vst.2d {w.wl}, [p1], d1", uses=[("w", "wl", 1)], mem=("st", "dst"), instr=ST_W),
    ]


def build(II=1, U=None):
    lp = Loop(ops(), classes={"x": list(range(12)), "dm": []})
    lp.schedule(II)
    lp.allocate(U)
    return lp


def check(lp, rows=3, per=9):
    n = rows * per
    n -= n % lp.U
    st = {"src": (lambda i: (i // per) * 320 + (i % per) * 32, dict(base=0x1000, dn=per - 1, dj=32, m=320 - 32 * (per - 1))),
          "dst": (lambda i: (i // per) * 576 + (i % per) * 32, dict(base=0x8000, dn=per - 1, dj=32, m=576 - 32 * (per - 1)))}
    return lp.check(n, st)


def function(lp, name="cpy32", drain=4):
    L = [f"\t.section\t.text.{name},\"ax\",@progbits", f"\t.globl\t{name}", "\t.p2align\t4", f"\t.type\t{name},@function", f"{name}:"]
    pre = ["mov\tdn0, r3", "mov\tdn1, r3", "mova\tdj0, #32", "mova\tdj1, #32", "mova\tdc0, #0", "mova\tdc1, #0",
           "mov\tm0, r1", "mov\tm1, r2",
           f"movxm\tls, #{name}_start", f"movxm\tle, #{name}_last", "add.nc\tlc, r0, #0", "nop", "nop", "nop", "nop", "nop", "nop"]
    L += ["\t" + p for p in pre]
    L += lp.emit_loop(name, drain=drain)
    L += ["\tret\tlr", "\tnop", "\tnop", "\tnop", "\tnop", "\tnop", f".Lfunc_end_{name}:", f"\t.size\t{name}, .Lfunc_end_{name}-{name}"]
    return L


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--ii", type=int, default=1)
    ap.add_argument("--u", type=int, default=None, help="unroll (body = U * II bundles)")
    ap.add_argument("--func", default="cpy32")
    ap.add_argument("--fit", action="store_true", help="round 13: compact the loop body (r12/asmfit.py)")
    o = ap.parse_args()
    lp = build(o.ii, o.u)
    cyc, land = check(lp)
    print(f"II {lp.II}, U {lp.U}, stages {lp.stages()}; check OK ({cyc} cycles for 27 units)")
    import asmfit
    asmfit.emit(lp, lambda: "\t.text\n" + "\n".join(function(lp, o.func)) + "\n", o.func, o.out, o.fit)
    Path(o.out).with_suffix(".h").write_text(f"// generated by r12/gen_copy.py\n#define CPY32_U {lp.U}\n")
    print("wrote", o.out)


if __name__ == "__main__":
    main()
