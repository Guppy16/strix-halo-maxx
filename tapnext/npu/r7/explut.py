"""exp(d) table for the attention's P (round 7): aie::lut<4, float, bfloat16> layout as r6/lutgen.py.

Segments of 2^STEP on [LO, HI); the first ZSEG segments are zero (P = 0 for d < LO + ZSEG h: e^-10 = 4.5e-5 of the
row max, harmless on real scores, r7/expemu.py), the rest a line per segment with the bf16 slope of the relative
least-squares fit and the fp32 offset that minimises the max relative error for that rounded slope.
The device: d = s - m (fp32, exact), dh = bf16(d), dl = bf16(d - dh), i = floor(dh / h) + BIAS,
p = off_i + slope_i dh + slope_i dl (fp32), then bfp16 straight from the fp32 accumulator.

usage: python3 r7/explut.py [out.h] [scale]   (also writes r7/aexp_lut.npz, unscaled, for the emulator)
scale: the kernel keeps the scores unscaled (s' = s / scale, exact for scale = 2^-k), so the table holds slope x scale
(exact in bf16) and the kernel's index shift drops by k; the offsets are unchanged.
"""

import sys
from pathlib import Path

import numpy as np
from ml_dtypes import bfloat16

HERE = Path(__file__).resolve().parent
LO, HI, STEP, ZSEG = -11.0, 9.0, -2, 4


def best_off(xs, y, a):
    """offset minimising max |a x + b - y| / y for a fixed slope (bisection on the two error ends)"""
    lo, hi = float((y - a * xs).min()), float((y - a * xs).max())
    for _ in range(80):
        b = (lo + hi) / 2
        e = (a * xs + b - y) / y
        if e.max() > -e.min():
            hi = b
        else:
            lo = b
    return (lo + hi) / 2


def table():
    h = 2.0 ** STEP
    n = int(round((HI - LO) / h))
    sl, of = np.zeros(n, np.float32), np.zeros(n, np.float32)
    for i in range(ZSEG, n):
        xs = np.linspace(LO + i * h, LO + (i + 1) * h, 513)[:-1]
        y = np.exp(xs)
        a, _ = np.polyfit(xs, y, 1, w=1 / y)
        a = float(np.float32(a).astype(bfloat16))
        sl[i], of[i] = a, np.float32(best_off(xs, y, a))
    return sl, of


def layout(sl, of):
    e = np.stack([sl, of], 1)
    g = e.reshape(len(sl) // 4, 1, 4, 2)
    return np.concatenate([g, g], 1).reshape(-1).astype(np.float32)  # each group of 4 entries twice


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else str(HERE.parent / "exp_lut.h")
    scale = float(sys.argv[2]) if len(sys.argv) > 2 else 1.0
    sl, of = table()
    assert len(sl) % 4 == 0 and np.log2(scale) == round(np.log2(scale))
    t = layout(sl * np.float32(scale), of)
    bias = int(round(-LO / 2.0 ** STEP))
    body = ",\n  ".join(", ".join(f"{v:.9e}f" for v in t[i:i + 8]) for i in range(0, len(t), 8))
    h = ("#pragma once\n"
         f"// exp(d) for the attention's P: {len(sl)} segments of 2^{STEP} on [{LO}, {HI}), the first {ZSEG} zero, bias {bias}\n"
         "// (aie::lut<4, float, bfloat16> layout; generated by r7/explut.py). One copy here (core data area); attn_begin\n"
         "// writes the second copy (another bank) into the C object's free tail.\n"
         f"// slopes x {scale} (the kernel's scores are s / {scale})\n"
         f"constexpr int AEXP_N = {len(sl)}, AEXP_STEP = {STEP}, AEXP_BIAS = {bias};\n"
         f"constexpr float AEXP_SLOPE_SCALE = {scale}f;\n"
         f"constexpr float AEXP_LO = {LO}f, AEXP_HI = {HI}f;\n"
         f"alignas(64) float aexp_ab[{len(t)}] = {{\n  {body}}};\n")
    Path(out).write_text(h)
    np.savez(HERE / "aexp_lut.npz", slopes=sl, offsets=of, lo=LO, hi=HI, step=STEP)
    xs = np.linspace(LO + ZSEG * 2.0 ** STEP, HI, 200001)[:-1]
    i = np.floor((xs - LO) / 2.0 ** STEP).astype(int)
    rel = (of[i].astype(np.float64) + sl[i].astype(np.float64) * xs) / np.exp(xs) - 1
    print(f"wrote {out}: {len(sl)} segments, {t.nbytes} B per copy; max |rel err| {np.abs(rel).max():.2e} "
          f"rms {np.sqrt(np.mean(rel ** 2)):.2e} (exact argument)")


if __name__ == "__main__":
    main()
