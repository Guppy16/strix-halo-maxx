"""Round 12: flat-edge GELU tables (npu-research ANALYSIS rev 6 §2.3).

The deployed tables (gelu_lut.h, r6/lutgen.py) hold 64 segments of 1/8 on [-4, 4); the kernels clamp x into
[-4, 3.984375] (xc) and compute s = offset + slope * xc. A flat-edge table adds one group of 4 segments on each side with
slope 0 and offset = the fp32 value the deployed kernel computes at the clamp edge (offset_0 + slope_0 * -4, offset_63 +
slope_63 * 3.984375). With the index clamped into [-4.125, 4.09375] the out-of-range x land in those flat segments and the
s MAC may take the UNCLAMPED x (off + 0 * x = off): bit-identical for every finite x, and the clamped xc is needed only for
the index (no xc ring in the asm loop).

Real segments keep their exact float values (parsed from gelu_lut.h, whose 9-digit decimals round-trip fp32); the bias
becomes 36 (LUT_BIAS_B 576). The fp32 edge value is the exact sum rounded once (the MAC: exact bf16 x bf16 product, fp32
accumulate); r12 apb checks it on the device against the deployed kernel over every finite bf16.

    python3 r12/lutflat.py [gelu_lut.h] [out.h]      (numpy)
"""

import re
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
EDGE_LO, EDGE_HI = -4.0, 3.984375  # the deployed clamp (SGELU_LO, SGELU_HI - 1/64)
IDX_LO, IDX_HI = -4.125, 4.09375  # index clamp of the flat tables: floor(8 x) in [-33, 32] -> segments 3 .. 68


def parse(text, name):
    m = re.search(rf"float {name}\[(\d+)\][^=]*= \{{(.*?)\}};", text, re.S)
    vals = np.array([float(v.rstrip("f")) for v in re.findall(r"-?\d\.\d+e[-+]\d+f", m.group(2))], np.float32)
    assert len(vals) == int(m.group(1)), name
    return vals


def entries(t):
    """[n][2] (slope, offset) from the stored layout (groups of 4 entries stored twice)"""
    g = t.reshape(-1, 2, 4, 2)
    assert np.array_equal(g[:, 0], g[:, 1])
    return g[:, 0].reshape(-1, 2)


def layout(e):
    g = e.reshape(-1, 1, 4, 2)
    return np.concatenate([g, g], 1).reshape(-1).astype(np.float32)


def edge(e, i, xc):
    slope, off = np.float64(e[i, 0]), np.float64(e[i, 1])
    return np.float32(off + slope * xc)  # exact in float64 (bf16 x bf16 product + fp32), one rounding to fp32


def flat(e):
    lo, hi = edge(e, 0, EDGE_LO), edge(e, len(e) - 1, EDGE_HI)
    pad = lambda v: np.array([[0.0, v]] * 4, np.float32)  # noqa: E731
    return np.concatenate([pad(lo), e, pad(hi)]), lo, hi


def emit(text, name):
    out = ""
    for copy in ("ab", "cd"):
        t = parse(text, f"{name}_{copy}")
        e, lo, hi = flat(entries(t))
        body = ",\n  ".join(", ".join(f"{v:.9e}f" for v in layout(e)[i:i + 8]) for i in range(0, 4 * len(e), 8))
        # after the declarator (also valid in a namespace); GELU_FLAT_AB_SEC lets a bench place the ab copy (default: data area)
        sec = ' __attribute__((section(".aie.bank3")))' if copy == "cd" else " GELU_FLAT_AB_SEC"
        out += f"alignas(64) float {name}_{copy}[{4 * len(e)}]{sec} = {{\n  {body}}};\n"
    U = name.upper()
    head = (f"// {name}: 72 segments of 2^-3 on [-4.5, 4.5): the deployed 64 on [-4, 4) + 4 flat ones per side (slope 0, offset = the\n"
            f"// fp32 value at the clamp edge: {lo:.9e} / {hi:.9e})\n"
            f"constexpr int {U}_N = 72, {U}_STEP = -3, {U}_BIAS = 36;\n"
            f"constexpr float {U}_LO = -4.0f, {U}_HI = 4.0f;  // the C++ clamp (unchanged); the asm index clamp: [{IDX_LO}, {IDX_HI}]\n")
    return head + out


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "gelu_lut.h"
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE.parent / "gelu_lut_flat.h"
    text = src.read_text()
    for name in ("sgelu", "serf"):  # the two copies must agree
        assert np.array_equal(parse(text, f"{name}_ab"), parse(text, f"{name}_cd"))
    h = ("#pragma once\n// generated by r12/lutflat.py from gelu_lut.h: flat-edge GELU tables (mm8.cc -DGELU_FLAT)\n"
         "#ifndef GELU_FLAT_AB_SEC\n#define GELU_FLAT_AB_SEC\n#endif\n"
         + emit(text, "sgelu") + emit(text, "serf"))
    # round trip: the real segments are bit-identical to the source tables
    for name in ("sgelu", "serf"):
        a, b = entries(parse(text, f"{name}_ab")), entries(parse(h, f"{name}_ab"))
        assert np.array_equal(a.view(np.uint32), b[4:-4].view(np.uint32)), name
        assert np.all(b[:4, 0] == 0) and np.all(b[-4:, 0] == 0)
    dst.write_text(h)
    print("wrote", dst)


if __name__ == "__main__":
    main()
