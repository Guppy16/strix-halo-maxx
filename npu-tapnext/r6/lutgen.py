"""Piecewise-linear LUT tables for aie::linear_approx<bfloat16, aie::lut<4, float, bfloat16>> (round 6).

The device computes, per lane: i = floor(x * 2^-step_bits) + bias; out = slope[i] * x + offset[i] (fp32 offset,
bf16 slope, exact product, fp32 accumulate). Layout (as aie_runtime_lib/AIE2P tanh_lut_ab): (slope, offset) float
pairs, groups of 4 entries stored twice in a row, and the same table again in a second bank (ab / cd).
Each segment's slope is the least-squares slope rounded to bf16, the offset then refit in fp32 for that slope.
"""

import numpy as np
from ml_dtypes import bfloat16


def s_gelu(x):
    """gelu(x) / x for the tanh form: 0.5 (1 + tanh(u))"""
    x = np.asarray(x, np.float64)
    return 0.5 * (1 + np.tanh(0.7978845608028654 * (x + 0.044715 * x ** 3)))


def s_erf(x):
    """gelu(x) / x for the exact (erf) form torch's nn.GELU() uses: Phi(x)"""
    from math import erf, sqrt
    x = np.asarray(x, np.float64)
    return 0.5 * (1 + np.vectorize(erf)(x / sqrt(2)))


def s_sig(x):
    return 1 / (1 + np.exp(-np.asarray(x, np.float64)))


def fit(fn, lo, hi, step_bits):
    w = 2.0 ** step_bits  # segment width (step_bits < 0)
    n = int(round((hi - lo) / w))
    slopes, offsets = [], []
    for i in range(n):
        xs = np.linspace(lo + i * w, lo + (i + 1) * w, 257)[:-1]
        a, b = np.polyfit(xs, fn(xs), 1)
        a = float(np.float32(a).astype(bfloat16))
        b = float(np.float32(np.mean(fn(xs) - a * xs)))
        slopes.append(a)
        offsets.append(b)
    return np.array(slopes, np.float32), np.array(offsets, np.float32)


def layout(slopes, offsets):
    e = np.stack([slopes, offsets], 1)  # [n][2]
    n = len(e)
    assert n % 4 == 0
    g = e.reshape(n // 4, 1, 4, 2)
    return np.concatenate([g, g], 1).reshape(-1).astype(np.float32)  # each group of 4 entries twice


def emit(name, lo, hi, step_bits, fn, banks=("1", "3")):
    sl, of = fit(fn, lo, hi, step_bits)
    t = layout(sl, of)
    bias = int(round(-lo / 2.0 ** step_bits))
    body = ",\n  ".join(", ".join(f"{v:.9e}f" for v in t[i:i + 8]) for i in range(0, len(t), 8))
    h = (f"// {name}: {len(sl)} segments of 2^{step_bits} on [{lo}, {hi}), bias {bias} (generated by r6/lutgen.py)\n"
         f"constexpr int {name.upper()}_N = {len(sl)}, {name.upper()}_STEP = {step_bits}, {name.upper()}_BIAS = {bias};\n"
         f"constexpr float {name.upper()}_LO = {lo}f, {name.upper()}_HI = {hi}f;\n")
    for bank, tag in zip(("ab", "cd"), banks):  # the two copies must sit in different memory banks
        sec = "" if tag == "data" else f"__attribute__((section(\".aie.bank{tag}\"))) "  # "data": the core's data area
        h += f"{sec}alignas(64) float {name}_{bank}[{len(t)}] = {{\n  {body}}};\n"
    np.savez(f"{name}_lut.npz", slopes=sl, offsets=of, lo=lo, hi=hi, step_bits=step_bits)
    return h


if __name__ == "__main__":
    import sys
    step = int(sys.argv[1]) if len(sys.argv) > 1 else -3
    out = sys.argv[2] if len(sys.argv) > 2 else "gelu_lut.h"
    if "sig" in out:  # the EW cores' sigmoid table: [0, 8), sigma(-z) = 1 - sigma(z)
        banks = tuple(sys.argv[3].split(",")) if len(sys.argv) > 3 else ("2", "3")
        open(out, "w").write("#pragma once\n// sigmoid tables for aie::lut<4, float, bfloat16> lookups (ew8.cc via nk8 sigmoid_lut_n)\n"
                             + emit("ssig", 0.0, 8.0, step, s_sig, banks))
        print("wrote", out)
        sys.exit(0)
    banks = tuple(sys.argv[3].split(",")) if len(sys.argv) > 3 else ("0", "1")
    open(out, "w").write("#pragma once\n// GELU = x s(x) tables for aie::lut<4, float, bfloat16> lookups (mm8.cc gelu_lut_n)\n"
                         + emit("sgelu", -4.0, 4.0, step, s_gelu, banks) + emit("serf", -4.0, 4.0, step, s_erf, banks))
    print("wrote", out)
