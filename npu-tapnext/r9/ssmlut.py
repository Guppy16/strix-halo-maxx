"""Tables for the RG-LRU transcendentals by lookup (round 9; numerics chosen with r9/ssmemu.py on real activations).

  ssig   sigmoid(x), per-segment line on [SIG_LO, SIG_HI) in segments of 2^SIG_STEP (x clamped into the table: the
         tails below SIG_LO only feed log_a values that round to a = 1, mult = 0 exactly as torch's)
  sexp   2^f on [-1/2, 1/2) in EXP_N segments (a = exp(log_a) by range reduction: 2^n 2^f)
  ssqrt  exact bf16 sqrt mantissas: entry (exponent parity, 7 mantissa bits) -> bf16 bits of sqrt(2^(1-par) M) in
         [1, 2]; the kernel adds floor((E - 127) / 2) to the exponent
Float tables: aie::lut<4, float, bfloat16> layout ((slope, offset) pairs, groups of 4 entries stored twice in a row);
int16 table: runs of 16 entries stored twice in a row (aie_kernels vision/lut_inv.h, AIE2P). Each table twice: _ab and
_cd, best in different banks (one bank works: +1 cycle per 4-lane load, r9/lprobe.py): the includer defines
SSM_LUT_AB / SSM_LUT_CD, or per copy SEC_SSIG_AB etc., as section attributes.

usage: python3 r9/ssmlut.py [out.h]
"""

import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import ssmemu  # noqa: E402

SIG_LO, SIG_HI, SIG_STEP = -12.0, 8.0, -3
EXP_N = 64


def sig_table():
    return ssmemu.pwl(ssmemu.s_sig, SIG_LO, SIG_HI, SIG_STEP, rel=True)


def exp_table():
    return ssmemu.exp2_rr_table(EXP_N)


def sqrt_table():
    idx = np.arange(256)
    m = 1 + (idx & 0x7F) / 128.0
    par = (idx >> 7) & 1
    v = np.sqrt(np.where(par == 1, 1.0, 2.0) * m).astype(np.float32)
    return ssmemu.bits16(v).astype(np.int16)


def float_layout(sl, of):
    e = np.stack([sl, of], 1).astype(np.float32)
    assert len(e) % 4 == 0
    g = e.reshape(len(e) // 4, 1, 4, 2)
    return np.concatenate([g, g], 1).reshape(-1)


def int16_layout(t, run=16):
    g = np.asarray(t, np.int16).reshape(-1, 1, run)
    return np.concatenate([g, g], 1).reshape(-1)


def sec_default(name, t):
    """per-copy placement macro SEC_<NAME>_<AB|CD>, defaulting to SSM_LUT_<AB|CD>"""
    m = f"SEC_{name.upper()}_{t.upper()}"
    return f"#ifndef {m}\n#define {m} SSM_LUT_{t.upper()}\n#endif\n"


def emit_f(name, vals):
    body = ",\n  ".join(", ".join(f"{v:.9e}f" for v in vals[i:i + 8]) for i in range(0, len(vals), 8))
    return "".join(sec_default(name, t) + f"SEC_{name.upper()}_{t.upper()} alignas(64) float {name}_{t}[{len(vals)}] = {{\n  {body}}};\n" for t in ("ab", "cd"))


def emit_i(name, vals):
    body = ",\n  ".join(", ".join(str(int(v)) for v in vals[i:i + 16]) for i in range(0, len(vals), 16))
    return "".join(sec_default(name, t) + f"SEC_{name.upper()}_{t.upper()} alignas(64) int16_t {name}_{t}[{len(vals)}] = {{\n  {body}}};\n" for t in ("ab", "cd"))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else str(HERE / "ssm_lut.h")
    s, e, q = sig_table(), exp_table(), sqrt_table()
    h = ["#pragma once", "// generated by r9/ssmlut.py: RG-LRU tables (sigmoid, 2^f, exact sqrt mantissas)",
         "#ifndef SSM_LUT_AB", "#define SSM_LUT_AB", "#endif", "#ifndef SSM_LUT_CD", "#define SSM_LUT_CD", "#endif",
         f"constexpr int SSIG_N = {s.n}, SSIG_STEP = {SIG_STEP}, SSIG_BIAS = {int(round(-SIG_LO / 2.0 ** SIG_STEP))};",
         f"constexpr float SSIG_LO = {SIG_LO}f, SSIG_HI = {SIG_HI}f;",
         f"constexpr int SEXP_N = {EXP_N}, SEXP_STEP = {-int(np.log2(EXP_N))}, SEXP_BIAS = {EXP_N // 2};"]
    txt = "\n".join(h) + "\n" + emit_f("ssig", float_layout(s.sl, s.of)) + "#ifdef SSM_LUT_EXP\n" + emit_f("sexp", float_layout(e.sl, e.of)) + "#endif\n" + emit_i("ssqrt", int16_layout(q))
    Path(out).write_text(txt)
    print(f"wrote {out}: sig {s.n} segments ({s.n * 16} B per copy), exp {EXP_N} ({EXP_N * 16} B), sqrt 256 entries (1024 B)")


if __name__ == "__main__":
    main()
