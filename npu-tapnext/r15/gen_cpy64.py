"""Round 15 (EW out copies): a contiguous copy of 64 B vectors as a modulo-scheduled asm loop, one vector per cycle (II 1).

ew8.cc out_copy copies the SSM chunk's 96 output vectors (x, x-1, x-2 from the input ring, h from g_hout, the z panels) into
the output ring with copy_v, a Peano loop of 6 bundles per 2 vectors (~800 cycles per chunk with the calls, r9 PROF). Source
and destination are always in different L1 banks there (input ring bank 3, arena bank 2, output ring bank 0), so a vlda + vst
per cycle runs without bank stalls.

    extern "C" void cpy64(const void *src /*p0*/, void *dst /*p1*/, int trips /*r0*/)
copies trips * CPY64_U vectors of 64 B (src and dst 64 B aligned, not overlapping). The drain's garbage iterations only load
(up to CPY64_U * ... vectors past src's end are read, never written).

    python3 r15/gen_cpy64.py OUT.s
"""

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "r11"))
sys.path.insert(0, str(HERE.parent / "r12"))
from msched import Loop, Op  # noqa: E402

LDA_X = "VLDA_dmx_lda_x_pstm_nrm_imm"
ST_X = "VST_dmx_sts_x_pstm_nrm_imm"


def build():
    lp = Loop([Op("L", "lda", "vlda {v.x}, [p0], #64", defs=[("v", "x", 7)], mem=("ld", "src"), instr=LDA_X),
               Op("S", "st", "vst {v.x}, [p1], #64", uses=[("v", "x", 1)], mem=("st", "dst"), instr=ST_X)],
              classes={"x": list(range(12)), "dm": []})
    lp.schedule(1)
    lp.allocate(4)  # U | 16: the out copies are 16 or 32 vectors
    assert lp.stages() == lp.ops[-1].t + 1 and lp.ops[-1].t // lp.II == lp.stages() - 1  # the store in the last stage
    return lp


def function(lp, name="cpy64"):
    L = [f"\t.section\t.text.{name},\"ax\",@progbits", f"\t.globl\t{name}", "\t.p2align\t4", f"\t.type\t{name},@function", f"{name}:"]
    # the prologue gives the zero-overhead loop its setup distance (7 bundles >= 6)
    pre = [f"movxm\tls, #{name}_start", f"movxm\tle, #{name}_last", "add.nc\tlc, r0, #0"]
    L += ["\t" + x for x in pre]
    # the prologue in the full 16 B form: it is the loop's setup distance after add.nc (round 14: 6 two-byte nops ran the body once)
    pro, body = lp.program()
    L += [Loop.bundle([(o.slot, lp.text(o, i)) for o, i in b], full=True) for b in pro]
    L += [x for x in lp.emit_loop(name, drain=0) if not x.startswith("\t//")][len(pro):]
    L += ["\tret\tlr", "\tnop", "\tnop", "\tnop", "\tnop", "\tnop", f".Lfunc_end_{name}:", f"\t.size\t{name}, .Lfunc_end_{name}-{name}"]
    return L


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    o = ap.parse_args()
    lp = build()
    for n in (lp.U, 2 * lp.U, 4 * lp.U):
        lp.check(n, {"src": (lambda i: 64 * i, dict(base=0x10000, dn=0, dj=64, m=64)),
                     "dst": (lambda i: 64 * i, dict(base=0x20000, dn=0, dj=64, m=64))})
    print(f"II {lp.II}, U {lp.U}, stages {lp.stages()}; check OK")
    Path(o.out).write_text("\t.text\n" + "\n".join(function(lp)) + "\n")
    Path(o.out).with_suffix(".h").write_text(f"// generated by r15/gen_cpy64.py\n#define CPY64_U {lp.U}\n")
    print("wrote", o.out)


if __name__ == "__main__":
    main()
